#!/usr/bin/env bash
# Refreshes jetbrains/lock/MainSolutionPackageVersions.subset.xml from the full main-solution lock.
# usage: jetbrains/snapshot-lock.sh <path-to-MainSolutionPackageVersions.xml>
# The subset contains the resolved packages of Tomlyn.Signed, copied verbatim from the full lock.
set -euo pipefail
lock=$(realpath "$1")
fork=$(cd "$(dirname "$0")" && pwd)
root=$(dirname "$fork")
subset="$fork/lock/MainSolutionPackageVersions.subset.xml"

JB_PACKAGE_LOCK="$lock" "$fork/build.sh" restore -v quiet
assets="$root/artifacts/jetbrains/obj/project.assets.json"

mapfile -t ids < <(grep -oE '^    "[^"/]+/[^"/]+": \{' "$assets" | sed -E 's/^    "([^"/]+)\/.*/\1/' | sort -fu)
mkdir -p "$(dirname "$subset")"
{
  echo '<?xml version="1.0" encoding="utf-8"?>'
  echo '<!-- Generated by jetbrains/snapshot-lock.sh from the JetBrains main solution lock; the entries are verbatim, limited to Tomlyn.Signed restore dependencies. -->'
  echo '<Project xmlns="http://schemas.microsoft.com/developer/msbuild/2003">'
  echo '  <ItemGroup>'
  for id in "${ids[@]}"; do
    grep -iE "^\s*<PackageLock Include=\"${id//./\.}\" " "$lock" | tr -d '\r' | sed -E 's/^\s*/    /' || true
  done
  echo '  </ItemGroup>'
  echo '</Project>'
} > "$subset"
echo "Wrote $(grep -c '<PackageLock ' "$subset") entries of ${#ids[@]} resolved packages to $subset"
